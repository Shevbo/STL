#!/usr/bin/env bash
# Доставка почты между окнами В РАБОТАЮЩУЮ СЕССИЮ.
#
# ЗАЧЕМ. Будильник почты висел только на SessionStart, а сессия живёт часами:
# письмо, пришедшее в середине, окно не видело вовсе (11.08.2026 письма лежали
# 7 и 30 часов при работающих окнах). Внутри сессии Claude срабатывают только
# хуки, поэтому доставка возможна ровно через них — на ввод оператора и на
# каждый вызов инструмента.
#
# ПОЧЕМУ ЧЕРЕЗ КЭШ. Ходить по ssh из хука нельзя: рукопожатие стоит ~1.8 с, а
# хук на каждый вызов инструмента умножил бы это на всю работу. Поэтому хук
# ЧИТАЕТ локальный файл (миллисекунды), а обновляет его фоновая задача не чаще
# раза в REFRESH_S. Во время активной работы вызовы инструментов идут постоянно,
# так что файл всегда свежее REFRESH_S.
#
# ПОЧЕМУ ОДНА СТРОКА. Цена хука не в секундах, а в токенах: он печатается в
# контекст на каждом выстреле. Печатаем только КОМУ и СКОЛЬКО, и молчим совсем,
# когда почты нет. Тишина — нормальное состояние.
set -uo pipefail

CACHE="$HOME/.stl-devmsg-line"
STAMP="$CACHE.at"
REFRESH_S=10

# 1) Мгновенно отдать то, что уже известно.
[ -s "$CACHE" ] && cat "$CACHE"

# 2) Обновить в фоне, но не чаще REFRESH_S — иначе на каждый вызов инструмента
#    улетал бы свой ssh.
# Время и чтение метки — ВСТРОЕННЫМИ средствами bash, без forks: на Windows
# каждый запуск подпроцесса стоит десятки миллисекунд, а этот хук висит на
# КАЖДОМ вызове инструмента. Два fork'а ($(date) и $(cat)) удваивали его цену.
printf -v now '%(%s)T' -1
last=0
[ -s "$STAMP" ] && read -r last < "$STAMP" 2>/dev/null
[ -n "$last" ] || last=0
if [ $(( now - last )) -ge "$REFRESH_S" ]; then
  echo "$now" > "$STAMP"
  (
    out=$(ssh -o ConnectTimeout=4 -o BatchMode=yes hoster \
          'bash ~/apps/shectory-trader/scripts/devmsg.sh board --brief' 2>/dev/null)
    # Пустой ответ = почты нет ИЛИ связь легла. В обоих случаях молчим: ложная
    # тревога в каждом хуке хуже, чем её отсутствие, а за реальной просрочкой
    # следит крон на хостере, который шлёт оператору в Telegram.
    printf '%s' "$out" > "$CACHE.tmp" 2>/dev/null && mv -f "$CACHE.tmp" "$CACHE"
  ) >/dev/null 2>&1 &
fi
exit 0
