"""Календарь значимых событий, двигающих RI, BR, GD, Si — и разметка дней прогона.

ЗАКАЗ ОПЕРАТОРА 26.09.2026: собрать из открытых источников даты и время
значимых событий (заседания по ставке, запасы нефти и т.д.) и проверить на них
стратегию usopen по четырём инструментам за последний год.

ИСТОЧНИКИ (официальные календари, не агрегаторы):
- ЦБ РФ, решения по ключевой ставке: https://cbr.ru/dkp/cal_mp/
  Пресс-релиз в 13:30 МСК, восемь заседаний в год.
- ФРС США, заявление FOMC: https://www.federalreserve.gov/monetarypolicy/fomccalendars.htm
  14:00 по восточному времени во ВТОРОЙ день заседания, восемь заседаний в год.
- EIA, недельные запасы нефти: https://www.eia.gov/petroleum/supply/weekly/schedule.php
  Каждую среду в 10:30 по восточному времени (в праздничные недели сдвиг на день,
  сдвиги здесь НЕ учтены — это известная неточность).
- BLS, индекс потребительских цен США: https://www.bls.gov/schedule/news_release/cpi.htm
  08:30 по восточному времени.

ВРЕМЯ. Всё приводится к МСК (UTC+3, без перехода). У США переход на летнее время
есть, поэтому одно и то же событие приходит на час раньше или позже:
14:00 ET = 21:00 МСК летом и 22:00 зимой. Даты перехода зашиты ниже.

ЧЕГО ЗДЕСЬ НЕТ и почему: заседания ОПЕК+ нерегулярны, их даты переносятся и
объявляются за считанные дни, а в открытых календарях они расходятся между
источниками. Вносить их «примерно» нельзя: событие, поставленное не на тот день,
превращает проверку в шум. Если понадобятся — добавлять поимённо и из пресс-релизов.
"""
from __future__ import annotations

import datetime as dt

MSK = dt.timezone(dt.timedelta(hours=3))

# Переход США на летнее время: второе воскресенье марта — первое воскресенье ноября.
_US_DST = ((dt.date(2025, 3, 9), dt.date(2025, 11, 2)),
           (dt.date(2026, 3, 8), dt.date(2026, 11, 1)))


def _msk_from_et(d: dt.date, hh: int, mm: int) -> dt.datetime:
    """Восточное время США -> МСК. Летом разница 7 часов, зимой 8."""
    summer = any(a <= d <= b for a, b in _US_DST)
    shift = 7 if summer else 8
    return dt.datetime.combine(d, dt.time(hh, mm), MSK) + dt.timedelta(hours=shift)


# Заседания ЦБ РФ (дата решения), решение в 13:30 МСК.
CBR = ["2025-02-14", "2025-03-21", "2025-04-25", "2025-06-06", "2025-07-25",
       "2025-09-12", "2025-10-24", "2025-12-19",
       "2026-02-13", "2026-03-20", "2026-04-24", "2026-06-19", "2026-07-24",
       "2026-09-11", "2026-10-23", "2026-12-18"]

# Заявление FOMC — ВТОРОЙ день заседания, 14:00 ET.
FOMC = ["2025-01-29", "2025-03-19", "2025-05-07", "2025-06-18", "2025-07-30",
        "2025-09-17", "2025-10-29", "2025-12-10",
        "2026-01-28", "2026-03-18", "2026-04-29", "2026-06-17", "2026-07-29",
        "2026-09-16", "2026-10-28", "2026-12-09"]

# Индекс потребительских цен США, 08:30 ET.
CPI = ["2025-12-18", "2026-01-13", "2026-02-13", "2026-03-11", "2026-04-10",
       "2026-05-12", "2026-06-10", "2026-07-14", "2026-08-12", "2026-09-11",
       "2026-10-14", "2026-11-10", "2026-12-10"]


def eia_wednesdays(a: dt.date, b: dt.date) -> list[dt.date]:
    """Запасы нефти EIA: каждая среда окна. Праздничные сдвиги не учтены."""
    d = a + dt.timedelta(days=(2 - a.weekday()) % 7)
    out = []
    while d <= b:
        out.append(d)
        d += dt.timedelta(days=7)
    return out


def events(a: dt.date, b: dt.date) -> list[dict]:
    """Все события окна: дата, время МСК, тип, инструменты, на которые влияет."""
    out: list[dict] = []
    for s in CBR:
        d = dt.date.fromisoformat(s)
        if a <= d <= b:
            out.append({"date": d, "hh": 13, "mm": 30, "kind": "ставка ЦБ",
                        "symbols": ("RI", "Si")})
    for s in FOMC:
        d = dt.date.fromisoformat(s)
        if a <= d <= b:
            t = _msk_from_et(d, 14, 0)
            out.append({"date": d, "hh": t.hour, "mm": t.minute, "kind": "ставка ФРС",
                        "symbols": ("RI", "Si", "GD")})
    for s in CPI:
        d = dt.date.fromisoformat(s)
        if a <= d <= b:
            t = _msk_from_et(d, 8, 30)
            out.append({"date": d, "hh": t.hour, "mm": t.minute, "kind": "инфляция США",
                        "symbols": ("GD", "Si", "RI")})
    for d in eia_wednesdays(a, b):
        t = _msk_from_et(d, 10, 30)
        out.append({"date": d, "hh": t.hour, "mm": t.minute, "kind": "запасы нефти",
                    "symbols": ("BR",)})
    out.sort(key=lambda e: (e["date"], e["hh"], e["mm"]))
    return out


def main() -> None:
    a, b = dt.date(2025, 9, 26), dt.date(2026, 9, 26)
    ev = events(a, b)
    print(f"событий за год {a}..{b}: {len(ev)}")
    by: dict[str, int] = {}
    for e in ev:
        by[e["kind"]] = by.get(e["kind"], 0) + 1
    for k, n in sorted(by.items(), key=lambda x: -x[1]):
        t = next(e for e in ev if e["kind"] == k)
        print(f"  {k:16} {n:>3} шт, время МСК {t['hh']:02d}:{t['mm']:02d} "
              f"(зимой/летом отличается у событий США)")
    print("\nближайшие десять:")
    for e in ev[:10]:
        print(f"  {e['date']}  {e['hh']:02d}:{e['mm']:02d}  {e['kind']:16} "
              f"{', '.join(e['symbols'])}")


if __name__ == "__main__":
    main()
