"""Швы непрерывной склейки: где кончается один контракт и начинается следующий.

ЗАЧЕМ. `fetch_continuous_bars` сшивает бары ПЕРЕДНЕГО контракта день за днём и
базис между сериями НЕ выравнивает. На смене контракта цена скачет, и позиция,
пережившая шов, получает фантомную прибыль или убыток. Замер на RI за
2025-11..2026-08: три шва, худший 01.07.2026 на −13 690 пунктов = 22 946 ₽ на
контракт и 550 705 ₽ на позиции в 24 контракта — больше, чем итог всего
девятимесячного прогона. То есть шов способен перевернуть знак результата.

КАК ИЩЕМ. По самим барам, а не по календарю экспираций: склейка выбирает
передний контракт своим правилом (минимальная дата поставки среди торгуемых), и
фактический шов бывает не в день экспирации — на RI он пришёлся на 01.07, а
третий четверг июня это 18.06.

ДВА УСЛОВИЯ, и второе обязательно. Скачок цены сам по себе бывает и рыночным
(новость, гэп открытия). Но склейка переключает контракт ТОЛЬКО на границе дня,
поэтому шов обязан стоять на первом баре новых суток. Без этого условия резкое
внутридневное движение читалось бы как шов, и бэктест закрывал бы позицию на
ровном месте.
"""
from __future__ import annotations

# Порог относительного разрыва. Базис ближнего и следующего контракта RI это
# проценты, внутридневной разрыв между соседними МИНУТАМИ такого размера —
# исключение. Ниже 1% начинают попадать обычные утренние гэпы.
SEAM_JUMP_FRAC = 0.015


def _day(ts: int) -> int:
    return int(ts) // 86_400


def find_seam_indices(bars, min_jump: float = SEAM_JUMP_FRAC) -> set[int]:
    """Индексы баров, С КОТОРЫХ начинается новый контракт.

    Возвращает множество i: bars[i] уже принадлежит следующей серии, bars[i-1] —
    последний бар предыдущей.
    """
    out: set[int] = set()
    for i in range(1, len(bars)):
        prev, cur = bars[i - 1], bars[i]
        p = getattr(prev, "close", 0.0) or 0.0
        c = getattr(cur, "close", 0.0) or 0.0
        if p <= 0 or c <= 0:
            continue
        if abs(c - p) / p < min_jump:
            continue
        if _day(getattr(cur, "time", 0)) == _day(getattr(prev, "time", 0)):
            continue                     # внутридневной скачок — это рынок, не шов
        out.add(i)
    return out


def seam_plan(bars, warmup: int, min_jump: float = SEAM_JUMP_FRAC) -> tuple[set[int], set[int]]:
    """(закрыться_на, не_торговать_на) — что бэктест должен сделать вокруг швов.

    ЗАКРЫТЬСЯ за ДВА бара до шва, а не за один. Движок исполняет заявку по
    открытию СЛЕДУЮЩЕГО бара, поэтому выход, отданный на последнем баре старого
    контракта, нальётся уже по цене нового — то есть ровно по шву, ради ухода от
    которого всё и делается. Ошибку поймал тест, а не разбор.

    НЕ ТОРГОВАТЬ первые `warmup` баров новой серии: индикаторы всё ещё считаются
    по хвосту, в который входят бары ЧУЖОГО контракта, и на шве у них выброс.
    Для macd_shectory1 это 238 минут около четырёх раз в год — цена вопроса
    ничтожна против фантома в полмиллиона.
    """
    seams = find_seam_indices(bars, min_jump)
    close_at = {i - 2 for i in seams if i >= 2}
    mute: set[int] = set()
    for i in seams:
        mute.update(range(i, min(i + max(0, int(warmup)), len(bars))))
    return close_at, mute
