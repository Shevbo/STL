"""Smart orders for the OPERATOR's manual QUIK trading (STL-side watcher, v1).

Kinds (the classic community set — QUIK «стоп-заявки» / broker bracket orders):
  sl        stop-loss:    side=sell fires when price <= trigger (protect a long),
                          side=buy  fires when price >= trigger (protect a short).
  tp        take-profit:  side=sell fires when price >= trigger,
                          side=buy  fires when price <= trigger.
  trail_tp  trailing stop: optional activation level (trigger_price, 0 = active at
                          once), then tracks the best price and fires when it
                          retraces trail_offset POINTS from the peak (sell) /
                          trough (buy).
  trail_sl  ПОДТЯГИВАЮЩАЯ: то же ведение по экстремуму, но стережёт УЖЕ ОТКРЫТУЮ
                          ручную позицию. Уровень задаётся в пунктах ХУЖЕ текущей
                          цены и двигается ТОЛЬКО в сторону уменьшения убытка;
                          дошла цена до уровня — позиция закрывается. Отличий от
                          trail_tp два, и оба смысловые: уровня активации нет
                          (стережём с момента постановки, позиция уже в рынке), и
                          «блоки после сделки» запрещены — эта заявка ВЫХОДИТ, а
                          защитная пара после выхода открыла бы новую позицию.
  on_fill   conditional (order-sends-order): fires the child order the moment the
                          watched client_id reports FILLED — lets the operator
                          chain "entry -> attach SL+TP bracket".
  (OCO)     any order carrying the same non-empty oco_group cancels its siblings
                          when one of the group fires — SL+TP as a bracket.

Not implemented (surveyed, deliberately later): iceberg, scale/ladder,
time-activated. See docs/runbooks/smart-orders.md.

ARCHITECTURE / honesty: this v1 watches ticks INSIDE the STL process (1s loop)
and fires plain limit orders through the existing human place path — so smart
orders pause while STL is down (robots on the agent are unaffected; the operator
is the user here and sees the stand). v2 = native QUIK NEW_STOP_ORDER through
the Lua bridge (exchange-side triggering, survives everything) — needs a proto
extension + an operator Lua restart, so it could not ship overnight.

Fired child prices are made MARKETABLE (cross by a cushion) and are ALWAYS
quantized to the instrument price step — an off-grid price is rejected by QUIK
("не кратно шагу") and silently fills nothing (bit us live 2026-07-21).

Pure logic lives in evaluate(); the API/watcher wiring is in
trader/api/quik_smart_orders.py. No I/O in this module.
"""

from __future__ import annotations

import json
import math
import os
import time
import uuid
from dataclasses import asdict, dataclass, field

from trader import market_session

KINDS = ("sl", "tp", "trail_tp", "on_fill", "trail_sl", "corridor", "triangle",
         "grid")
# Типы, которые ведут уровень за экстремумом (храповик). Список общий, чтобы
# новый вид не пришлось дописывать в трёх местах и один из них не забыть.
_TRAILING = ("trail_tp", "trail_sl")

# Cross cushion for a fired (marketable) child: enough to actually cross after
# exchange lag, but safely under the 0.2% hard price collar.
_CUSHION_FRAC = 0.0005     # 0.05% of price
_CUSHION_MIN_STEPS = 3     # never less than 3 price steps
_CUSHION_MAX_FRAC = 0.0015 # hard cap, must stay under the 0.2% collar
_STALE_TICK_MS = 30_000    # never fire off a quote older than this


@dataclass
class SmartOrder:
    so_id: str
    kind: str                 # one of KINDS
    code: str                 # instrument, e.g. RIU6
    side: str                 # side of the CHILD order to fire: "buy" | "sell"
    qty: int
    trigger_price: float = 0.0   # sl/tp: level; trail_tp: activation level (0 = at once)
    trail_offset: float = 0.0    # trail_tp: retrace in PRICE POINTS
    watch_client_id: str = ""    # on_fill: client_id whose FILL fires the child
    child_price: float = 0.0     # on_fill: explicit child limit (0 = marketable)
    oco_group: str = ""          # same non-empty group = one-cancels-others
    good_till_ms: int = 0        # 0 = no expiry
    status: str = "armed"        # armed | fired | cancelled | expired | error
    note: str = ""
    sl_offset: float = 0.0       # ЛЮБОЙ тип: защитный стоп в ПУНКТАХ после входа (0 = без стопа)
    tp_offset: float = 0.0       # ЛЮБОЙ тип: тейк в ПУНКТАХ доходного хода после входа (0 = без тейка)
    trail_after: float = 0.0     # ЛЮБОЙ тип: ПОДТЯГИВАЮЩАЯ в пунктах после входа (0 = без неё)
    # ЛЮБОЙ тип: тейк после входа СЛЕДЯЩИЙ. tp_offset становится уровнем активации, дальше
    # тейк ведёт экстремум и закрывает на откате tp_trail пунктов. 0 = фиксированный тейк.
    # Фиксированный отдаёт движение ровно на уровне, следящий забирает продолжение (17.09.2026).
    tp_trail: float = 0.0
    # ЛЮБОЙ тип: блок после сделки ЦЕНОЙ УРОВНЯ вместо пунктов от входа. Оператор
    # видит коридор и ставит тейк под его границей; пунктами туда не попасть, пока
    # цена входа неизвестна (замечание оператора 18.09.2026). Уровень с пунктами
    # того же блока взаимоисключающи; следящий тейк берёт уровень как АКТИВАЦИЮ.
    sl_price: float = 0.0
    tp_price: float = 0.0
    parent_id: str = ""          # у защитного стопа — so_id заявки, которая его породила
    # Передача защиты под охрану терминала (native_protect.py): "" пока в STL,
    # sent - транзакция ушла, live - QUIK зарегистрировал, failed - не принял и
    # защиту снова стережёт STL, done - стоп-заявка отработала или снята.
    native_state: str = ""
    native_stop_num: str = ""    # номер стоп-заявки QUIK у ребёнка-держателя
    native_ms: int = 0
    # Когда ВПЕРВЫЕ увидели, что охранять нечего: позиции, которую эта защитная
    # заявка закрывает, в рынке нет. 01.10.2026 два стопа оператора на покупку 40
    # и 13 простояли взведёнными 34 минуты после того, как охраняемый шорт на 53
    # исчез, и до уровня оставалось 230 пунктов: сработав, они открыли бы лонг на
    # 53 контракта с нуля. Ноль = охранять есть что (или мы ещё не смотрели).
    flat_since_ms: int = 0
    # Видели ли хоть раз позицию, которую эта защитная заявка закрывает.
    # Без этого признака списание осиротевших трогало ВХОДЫ оператора: голый
    # tp/sl/trail_tp без блоков после сделки при флэте по инструменту выглядит
    # неотличимо от защиты, пережившей свою позицию. Разница только одна —
    # у защиты позиция БЫЛА, у входа её не было никогда (ревью 01.10.2026).
    guarded_seen: bool = False
    # Когда запись стоп-заявки ПОСЛЕДНИЙ РАЗ видели живой в таблице терминала.
    # Нужен, чтобы отличить исполнение от снятия по сроку: у стоп-заявки QUIK срок
    # жизни - торговый день, и утром она исчезает сама (23.09.2026 так молча
    # пропала следящая продажа 30 контрактов).
    native_seen_ms: int = 0
    peak: float = 0.0            # trail bookkeeping (best price since activation)
    activated: bool = False      # trail: activation level crossed
    created_ms: int = 0
    fired_ms: int = 0
    fired_client_id: str = ""
    fired_price: float = 0.0     # РЕАЛЬНАЯ средняя цена исполнения дочерней заявки
    fired_qty: int = 0           # сколько контрактов реально исполнилось
    # ГАРАНТИРОВАННЫЙ ВЫХОД ЗА ТРИ ФАЗЫ (заказ оператора 29.09.2026). Стоп ставит
    # ЛИМИТНУЮ заявку, и на быстром движении она не наливается: его собственный
    # стоп на 70 RIZ6 сработал в 14:50:06 с лимитом в 30 пунктов от уровня, рынок
    # за минуту прошёл 690 пунктов, заявка умерла нетронутой и позиция осталась
    # открытой. Поэтому защита больше не «поставил и жду»:
    #   фаза 1 (esc_hold_sec)   стоим у планки — лучшая цена, если рынок вернётся;
    #   фаза 2 (esc_chase_sec)  переставляем каждые esc_chase_every_sec за ценой;
    #   фаза 3                  бьём по рынку (лимит у границы коллара).
    # Ноль в esc_hold_sec/esc_chase_sec выключает свою фазу; оба нуля = сразу по
    # рынку. Счётчик времени идёт от fired_ms, то есть от выстрела.
    esc_hold_sec: int = 0        # 0 = взять из профиля
    esc_chase_sec: int = 0       # 0 = взять из профиля
    esc_chase_every_sec: int = 0 # 0 = взять из профиля
    # Профиль доведения до исполнения (вход И выход): aggressive | active |
    # normal, настраиваются оператором в data/exec_profiles.json. Пустой =
    # штатный. Явные esc_* ниже, если заданы, ПЕРЕКРЫВАЮТ профиль: разовая
    # заявка не должна требовать правки общей настройки.
    esc_profile: str = ""
    esc_last_ms: int = 0         # когда последний раз переставляли
    esc_market: bool = False     # фаза 3 уже отработала: больше не трогаем
    # ── КОРИДОР (kind="corridor", заказ оператора 29.09.2026) ──────────────────
    # Торговля от стенок наклонного канала: продаём у верхней, покупаем у нижней,
    # каждое касание противоположной стенки = ПЕРЕВОРОТ (сделка вдвое: закрыть и
    # открыть). Верхняя граница — прямая через две точки (время, цена); нижняя ей
    # ПАРАЛЛЕЛЬНА и проходит через c_low в момент c_t1_ms. Равные цены точек =
    # горизонтальный коридор. Уход за стенку дальше c_stop_pts — выход, и выход
    # гарантированный: коридор пользуется той же трёхфазной эскалацией, что стоп.
    c_t1_ms: int = 0
    c_p1: float = 0.0
    c_t2_ms: int = 0
    c_p2: float = 0.0
    c_low: float = 0.0           # цена нижней границы в момент c_t1_ms
    # ТРЕУГОЛЬНИК (kind="triangle"): у нижней границы СВОЙ угол, поэтому нужна её
    # вторая точка. Ширина канала меняется — сужается (клин сходится) или
    # расширяется. У коридора это поле пустое: там нижняя параллельна верхней.
    c_low2: float = 0.0          # цена нижней границы в момент c_t2_ms
    # ── СЕТКА («радиация», kind="grid", заказ оператора 30.09.2026) ───────────
    # Непрерывная самовозобновляемая сетка: g_buys уровней покупки ВНИЗ и g_sells
    # уровней продажи ВВЕРХ от цены постановки, шаг g_step пунктов, объём g_lot на
    # уровень. Уровни ФИКСИРОВАНЫ на весь срок: исполнилась заявка — на её место
    # встаёт встречная, и сетка живёт дальше сама. Заявки выставляются в QUIK
    # СРАЗУ, чтобы стоять в стакане, а не ждать сторожа: оператор торгует
    # ликвидность, и опоздание на такт здесь и есть весь проигрыш.
    # Стоп за последним уровнем (g_stop_pts) закрывает позицию и ЗАВЕРШАЕТ сетку.
    g_step: float = 0.0          # шаг сетки в пунктах
    g_buys: int = 0              # сколько уровней покупки вниз
    g_sells: int = 0             # сколько уровней продажи вверх
    g_lot: int = 0               # объём на один уровень
    g_base: float = 0.0          # цена постановки: от неё считаются уровни
    g_stop_pts: float = 0.0      # стоп за последним уровнем, в пунктах (0 = без стопа)
    g_live: dict = field(default_factory=dict)   # уровень -> client_id стоящей заявки
    g_pos: int = 0               # позиция сетки: + лонг, − шорт
    g_avg: float = 0.0           # средняя цена ОТКРЫТОЙ позиции сетки (0 = вне рынка)
    # РЕЖИМ «ТОЛЬКО НА ВЫХОД»: заявка доводит свою позицию до закрытия и больше
    # ничего не открывает, причём закрывает ТОЛЬКО БЕЗ УБЫТКА — по цене не хуже
    # средней входа (требование оператора 02.10.2026). Снимается тем же
    # переключателем. У роботов такой режим есть с 28.07.2026 и работает так же,
    # с одним отличием: там выход идёт по сигналу стратегии и цена не проверяется,
    # здесь выход идёт уровнями, и цену проверяем.
    exit_only: bool = False
    # ЗАЩИТА СЕТКИ: после N исполненных уровней ИЛИ ухода цены от базы на X% сетка
    # сама переходит в режим «только на выход». Спецификация окна backtests,
    # решение оператора 02.10.2026; числа из пятой редакции бэктеста
    # (docs/grid-regime-filter-2026.md): убыток на отложенной трети сокращается в
    # 11-15 раз (−288/−399/−366 -> −23/−27/−27 тыс ₽ УЖЕ С КОМИССИЕЙ), закрытий по
    # безубытку 81%, по стопу 7%. Прибыльной сетку это не делает — это ограничитель
    # ущерба. 0 выключает условие.
    g_trig_fills: int = 0        # сколько исполненных уровней включают защиту
    g_trig_move_pct: float = 0.0  # уход цены от базы в процентах, который её включает
    g_fills_done: int = 0        # исполненных уровней с момента взведения
    g_trig_ms: int = 0           # когда защита включилась (0 = ещё нет)
    # ПЕРЕВЗВЕДЕНИЕ ПОСЛЕ ЧИСТОГО ВЫХОДА. Требование оператора 02.10.2026: выйдя по
    # защите без убытка, та же сетка через заданный срок встаёт снова. Смысл в том,
    # что защита убирает сетку из ТРЕНДА, а не из рынка: когда движение выдохлось,
    # сетка снова уместна. 0 = не перевзводить, выход окончателен.
    g_rearm_min: float = 0.0     # через сколько минут после выхода вставать снова
    g_rearm_at_ms: int = 0       # когда именно (0 = не запланировано)
    g_rearms: int = 0            # сколько раз уже перевзводилась
    # КАСАНИЯ ТРИГГЕРНОЙ ЦЕНЫ — отдельный счётчик, не филлы уровней. Одиночный
    # выброс не должен снимать сетку: цена ткнулась в порог и вернулась — это шум,
    # а не тренд. Защита по ходу цены срабатывает на N-м ВОЗВРАЩЕНИИ в зону, а не
    # на каждом тике внутри неё.
    # Считаются ПО СТОРОНАМ ОТДЕЛЬНО (уточнение оператора 02.10.2026): снимать
    # сетку должен ОДНОСТОРОННИЙ уход. Чередование вверх-вниз это колебание вокруг
    # базы, то есть ровно то, ради чего сетка и стоит, — суммировать такие касания
    # значило бы выключать сетку в её рабочем режиме.
    # ВЫХОД ПО ЦЕЛИ ПРИБЫЛИ (требование оператора 02.10.2026). Сетка без тейка
    # может ходить вокруг базы сколько угодно: уровни гасятся и оживают, прибыль
    # копится и снова растворяется. Цель забирает её со стола и ЗАКАНЧИВАЕТ сетку.
    # Считается в рублях: оператор думает деньгами счёта, а не пунктами.
    g_tp_rub: float = 0.0        # цель прибыли в рублях, 0 = без цели
    # Денежный поток сетки в ПУНКТАХ: продажа прибавляет, покупка вычитает.
    # Прибыль = поток + открытая позиция по рынку. Через поток, а не через
    # «средняя минус цена», потому что сетка закрывает части позиции вразнобой и
    # средняя после частичного сокращения уже не описывает заработанное.
    g_cash_pts: float = 0.0
    g_cash_on: bool = False      # поток ведётся (база заведена)
    # ОКНО ВЫСТАВЛЕННЫХ УРОВНЕЙ (оператор 02.10.2026: «в радиации не надо
    # выставлять все заявки сразу. только пять сверху и пять снизу. остальные в
    # STL»). В QUIK стоят N ближайших к рынку уровней с каждой стороны, остальные
    # ждут в STL и выставляются, когда рынок к ним подходит. Сорок заявок по 3-5
    # контрактов держали ГО под всю сетку сразу (свободных средств 25%), хотя
    # дальние уровни часами не исполняются. 0 = выставлять все, как раньше.
    g_window: int = 5
    g_trig_touches: int = 1      # сколько касаний С ОДНОЙ стороны нужно
    g_touch_up: int = 0          # касаний верхнего порога
    g_touch_down: int = 0        # касаний нижнего порога
    g_zone_side: str = ""        # где цена сейчас: "up" | "down" | "" (внутри)
    g_done: bool = False         # уровни больше не выставляем
    # client_id РЫНОЧНОЙ заявки, которой стоп закрывает позицию сетки. Пока она в
    # пути, статус умной заявки "closing": сетка уже не торгует, но и законченной
    # не является. Без этого ожидания «сетка снята» означало бы «заявку отправили»,
    # а 29.09.2026 рыночная заявка нативного стопа на 70 контрактов сработала и
    # умерла с НУЛЁМ исполнения — отправить и закрыть это разные события.
    g_close_cid: str = ""
    c_stop_pts: float = 0.0      # выход за стенку в пунктах (0 = без стопа)
    c_flips_max: int = 0         # сколько переворотов разрешено (0 = без предела)
    c_flips: int = 0             # сколько уже сделано
    c_pos: int = 0               # позиция коридора: + лонг, − шорт, 0 вне рынка
    c_avg: float = 0.0           # средняя цена ОТКРЫТОЙ позиции коридора
    c_qty: int = 0               # БАЗОВЫЙ объём стороны (qty мутируется под заявку)
    # Заявки коридора/треугольника СТОЯТ В СТАКАНЕ на обеих стенках (оператор,
    # 30.09.2026): к моменту касания заявка должна быть уже в очереди, а не
    # выставляться в эту секунду. Стенки движутся, поэтому заявки переставляются
    # вслед за линией; здесь — client_id стоящей заявки на каждой стенке.
    c_live: dict = field(default_factory=dict)
    c_done: bool = False         # переворты исчерпаны или стоп сработал

    def validate(self, reference_price: float = 0.0) -> str | None:
        """Returns a human error or None. Kept dumb and explicit.

        reference_price - цена инструмента (рыночная или уровень заявки), если она
        известна вызывающему: по ней ловится ЦЕНА, введённая в поле ПУНКТОВ."""
        if self.kind not in KINDS:
            return f"kind должен быть одним из {KINDS}"
        if self.side not in ("buy", "sell"):
            return "side должен быть buy|sell"
        if self.qty <= 0:
            return "qty должен быть > 0"
        if not self.code:
            return "code обязателен"
        if self.kind in ("sl", "tp") and self.trigger_price <= 0:
            return "trigger_price обязателен для sl/tp"
        if self.kind in ("corridor", "triangle"):
            if self.kind == "triangle" and self.c_low2 <= 0:
                return "треугольник: нужна вторая точка нижней границы (c_low2)"
            if self.kind == "triangle" and self.c_low2 >= self.c_p2:
                return "треугольник: во второй точке нижняя граница не ниже верхней"
            if self.c_p1 <= 0 or self.c_p2 <= 0:
                return "коридор: обе точки верхней границы обязательны"
            if self.c_low <= 0:
                return "коридор: уровень нижней границы обязателен"
            if self.c_t2_ms <= self.c_t1_ms:
                return "коридор: вторая точка должна быть ПОЗЖЕ первой"
            if self.c_low >= min(self.c_p1, self.c_p2):
                return "коридор: нижняя граница должна быть ниже верхней"
        if self.kind == "grid":
            if self.g_step <= 0:
                return "сетка: шаг обязателен и должен быть > 0"
            if self.g_buys < 0 or self.g_sells < 0 or (self.g_buys + self.g_sells) == 0:
                return "сетка: нужен хотя бы один уровень покупки или продажи"
            if self.g_lot <= 0:
                return "сетка: объём на уровень обязателен"
            if self.g_base <= 0:
                return "сетка: не известна цена постановки"
            if (self.sl_offset or self.tp_offset or self.trail_after or self.tp_trail
                    or self.sl_price or self.tp_price):
                return ("сетка ведёт позицию сама: блоки после сделки ей не ставятся")
        if self.kind in ("corridor", "triangle"):
            if self.c_flips_max < 0:
                return "коридор: число переворотов не может быть отрицательным"
            # Блоки после сделки коридору запрещены (просьба ui-ux 29.09.2026, и
            # она верна): он ведёт позицию сам — открывает, переворачивает,
            # закрывает по стопу. Защитный ребёнок пережил бы переворот и после
            # него открыл бы позицию в обратную сторону, то есть вошёл бы в рынок
            # без ведома оператора. Та же беда, от которой закрыта подтягивающая.
            if (self.sl_offset or self.tp_offset or self.trail_after or self.tp_trail
                    or self.sl_price or self.tp_price):
                return ("коридор ведёт позицию сам: блоки после сделки ему не "
                        "ставятся — переживший переворот стоп откроет позицию "
                        "в обратную сторону")
        if self.kind in _TRAILING and self.trail_offset <= 0:
            return f"trail_offset (пункты) обязателен для {self.kind}"
        if self.kind == "trail_sl":
            # Уровня активации у подтягивающей нет: позиция УЖЕ в рынке, стеречь
            # её надо с первого тика. Непустой trigger_price означал бы, что
            # оператор перепутал её со следящей, и позиция осталась бы без стопа
            # до пробоя уровня — молча.
            if self.trigger_price:
                return "у подтягивающей нет уровня активации: она стережёт позицию сразу"
            # Она ВЫХОДИТ из позиции, а «блоки после сделки» ВХОДЯТ. Разрешить их
            # здесь значит после закрытия открыть новую позицию в обратную сторону.
            if (self.sl_offset or self.tp_offset or self.trail_after or self.tp_trail
                    or self.sl_price or self.tp_price):
                return "подтягивающая закрывает позицию: блоки после сделки ей не ставятся"
        # Цена в поле пунктов. 18.09.2026 оператор ввёл в «активацию» тейка уровень
        # 84700; движок сложил его с входом 83510 и поставил активацию на 168210 -
        # недостижимую. Позиция осталась с одним стопом и без тейка, и это было
        # видно только в мелком тексте карточки. Блок после сделки - это РАССТОЯНИЕ
        # от входа: половина цены инструмента заведомо не расстояние.
        ref = reference_price or self.trigger_price
        if ref > 0:
            for what, value in (("защитный стоп", self.sl_offset), ("тейк", self.tp_offset),
                                ("подтягивающая", self.trail_after),
                                ("откат следящего тейка", self.tp_trail),
                                ("откат", self.trail_offset)):
                if value and value >= ref * _PRICE_IN_POINTS_FRAC:
                    return (f"{what}: {value:g} похоже на ЦЕНУ, а не на пункты. "
                            f"Здесь задаётся расстояние от входа в пунктах "
                            f"(цена инструмента около {ref:g})")
            for what, value in (("уровень стопа", self.sl_price), ("уровень тейка", self.tp_price)):
                if value and not (ref * 0.5 <= value <= ref * 2):
                    return (f"{what}: {value:g} слишком далеко от цены инструмента "
                            f"(около {ref:g}) - это цена уровня, а не пункты")
        if self.kind == "on_fill" and not self.watch_client_id:
            return "watch_client_id обязателен для on_fill"
        if self.sl_offset < 0 or self.tp_offset < 0 or self.trail_after < 0 or self.tp_trail < 0:
            return "блоки после сделки в пунктах не могут быть отрицательными"
        if self.sl_price and self.sl_offset:
            return "защитный стоп: задай либо пункты от входа, либо цену уровня, не оба"
        if self.tp_price and self.tp_offset:
            return "тейк: задай либо пункты от входа, либо цену уровня, не оба"
        if self.sl_price < 0 or self.tp_price < 0:
            return "цена уровня не может быть отрицательной"
        if self.sl_price and self.trail_after:
            return "после сделки нельзя ставить сразу обычный стоп и подтягивающую"
        if self.tp_trail and not (self.tp_offset or self.tp_price):
            # Без уровня активации тейк вёл бы экстремум с первого тика и закрыл бы
            # позицию на первом откате: в убытке, а не с прибылью.
            return "следящий тейк: задай tp_offset, прибыль, с которой тейк начинает следить"
        if self.sl_offset and self.trail_after:
            # Два стопа на одну позицию: сработает ближний, дальний останется
            # висеть и на следующем ходу ОТКРОЕТ позицию в обратную сторону.
            return "после сделки нельзя ставить сразу обычный стоп и подтягивающую"
        # Защитная пара разрешена ЛЮБОМУ типу (09.08.2026): любая умная заявка
        # только ВХОДИТ и после срабатывания забывает про позицию, поэтому «блоки
        # SL и TP после сделки» нужны везде, а не только у следящей и зависимой.
        # Рекурсии здесь нет по построению: сами защитные заявки создаёт
        # `_protective`, offset'ов он им не ставит — значит внуков не будет.
        return None


