def quantize(price: float, step: float, side: str) -> float:
    """Snap price onto the exchange grid: DOWN for sell, UP for buy — the
    conservative direction keeps a marketable order marketable."""
    if step <= 0:
        return price
    n = price / step
    snapped = math.floor(n) * step if side == "sell" else math.ceil(n) * step
    # float dust: 83533.12 -> 83530.0000001 style artifacts
    return round(snapped, 10)


def marketable_price(side: str, bid: float, ask: float, last: float, step: float) -> float:
    """Cross the current touch by a cushion, on-grid. sell -> below bid,
    buy -> above ask (fallback last when the book side is empty)."""
    base = (bid if side == "sell" else ask) or last
    if base <= 0:
        return 0.0
    cushion = min(max(_CUSHION_FRAC * base, _CUSHION_MIN_STEPS * step),
                  _CUSHION_MAX_FRAC * base)
    raw = base - cushion if side == "sell" else base + cushion
    return quantize(raw, step, side)


def market_price(side: str, bid: float, ask: float, last: float, step: float,
                 collar: float) -> float:
    """Цена «по рынку» в фазе 3: пробиваем спред на столько, сколько ПОЗВОЛЯЕТ
    коллар агента, с запасом в 10% от него. Настоящей рыночной заявки в этом
    протоколе нет (агент шлёт лимит и сам проверяет коллар), поэтому «по рынку»
    здесь — самый агрессивный лимит, который пройдёт проверку.
    """
    base = (bid if side == "sell" else ask) or last
    if base <= 0 or collar <= 0:
        return 0.0
    cushion = base * collar * 0.9
    raw = base - cushion if side == "sell" else base + cushion
    return quantize(raw, step, side)



# ── СЕТКА «РАДИАЦИЯ» ─────────────────────────────────────────────────────────
# Уровни нумеруются ЦЕЛЫМИ от нуля: −1, −2 … вниз (покупки), +1, +2 … вверх
# (продажи). Ноль — цена постановки, на нём заявки нет: сетка живёт вокруг него.
#
# Правило восстановления, ради которого всё и заводилось: исполнилась заявка на
# уровне k — на ТОТ ЖЕ уровень встаёт ВСТРЕЧНАЯ. Купили на −2, значит на −2
# теперь стоит продажа: она и есть тейк в один шаг сетки. Продали на +1 — на +1
# встаёт покупка. Уровни при этом не двигаются НИКОГДА (решение оператора
# 30.09.2026): плавающая сетка уехала бы за трендом и превратила бы шаг в
# случайную величину.


def grid_price(so: SmartOrder, level: int) -> float:
    return so.g_base + level * so.g_step


def grid_levels(so: SmartOrder) -> list[int]:
    """Все уровни сетки, ВКЛЮЧАЯ НОЛЬ — цену постановки.

    Ноль я сначала исключил, решив, что на цене постановки заявки быть не должно.
    Оператор указал на дыру в живой сетке 01.10.2026: база 85460, вокруг стоят
    85360 и 85560, а на самой 85460 пусто. Это не особый случай, а такой же
    уровень: рынок с него уходит, и тогда там обязана стоять заявка.

    От мгновенного исполнения ноль защищён тем же правилом, что и остальные:
    заявка по ту сторону рынка не выставляется. Пока рынок стоит ровно на базе,
    уровень просто ждёт — это состояние «не выставлен», а не пропажа.
    """
    return ([-i for i in range(1, so.g_buys + 1)] + [0]
            + [i for i in range(1, so.g_sells + 1)])


def grid_consumed(live: dict, level: int) -> bool:
    """Уровень уже отработал: на нём вошли, и лот от него сидит в позиции.

    Принимает САМ СЛОВАРЬ состояния, а не заявку. 01.10.2026 я написал эту
    проверку читающей so.g_live, тогда как филл внутри прохода сторожа пишет в
    ЛОКАЛЬНУЮ копию, а обратно она ложится только в конце цикла. В пределах
    одного прохода пометка была не видна, уровень выглядел пустым — и сторож
    ставил на него новую заявку в ту же секунду. Уровень 85560 так продал два
    контракта вместо одного. Один источник истины вместо двух: кто пишет, тот и
    читает.
    """
    return bool((live or {}).get(f"flip:{level}"))


def grid_side_for(so: SmartOrder, level: int, price: float = 0.0) -> str:
    """Чья заявка стоит на уровне СЕЙЧАС.

    В «радиации» НЕТ ПОНЯТИЯ ТЕЙКА, есть уровни (оператор, 01.10.2026). Сторона
    определяется только тем, по какую сторону РЫНКА уровень оказался: выше рынка
    продаём, ниже покупаем. Это же правило держит заявку от пересечения рынка —
    лимит по ту сторону исполнился бы мгновенно (30.09.2026, 43 контракта).

    Без цены (её не всегда передают) остаётся исходная лестница от базы: низ
    покупает, верх продаёт. Сторож без котировки заявок всё равно не ставит.
    """
    if price > 0:
        return "sell" if grid_price(so, level) > price else "buy"
    return "buy" if level < 0 else "sell"


def grid_window(so: SmartOrder, live: dict, price: float) -> tuple[set[int], set[int]]:
    """(какие уровни ставить, какие держать, если уже стоят).

    Ставим N ближайших к рынку ЖИВЫХ уровней с каждой стороны (погасший ждёт
    соседа и места в окне не занимает). Держим — N+2: уровень, вышедший из окна на
    один-два шага, не снимаем. Иначе цена, гуляющая вокруг одного уровня, гоняла
    бы дальний край окна туда-сюда снятием и постановкой, а каждая транзакция
    стоит денег (сверх 15 в секунду — 5 ₽ штука).
    """
    allv = set(grid_levels(so))
    if so.g_window <= 0 or price <= 0:
        return allv, allv
    lv = [lv_ for lv_ in grid_levels(so) if grid_places_here(live, lv_)]
    above = sorted((x for x in lv if grid_price(so, x) > price), key=lambda x: grid_price(so, x))
    below = sorted((x for x in lv if grid_price(so, x) < price), key=lambda x: -grid_price(so, x))
    # Уровень ровно на цене рынка места в окне не занимает: заявка на нём не
    # ставится (стояла бы впритык к рынку), и считать его значило бы выставить
    # четыре вместо пяти. Стоящую там заявку не снимаем.
    at = [x for x in lv if grid_price(so, x) == price]
    n = so.g_window
    return set(above[:n] + below[:n]), set(above[:n + 2] + below[:n + 2] + at)


def grid_places_here(live: dict, level: int) -> bool:
    """Нужна ли заявка на этом уровне прямо сейчас. Погасший уровень ждёт филла
    соседа, а не повтора входа по своей же цене."""
    return not grid_consumed(live, level)


def grid_stop_levels(so: SmartOrder) -> tuple[float, float]:
    """Где стоп: за последним уровнем сетки, вниз и вверх. (0,0) = без стопа."""
    if so.g_stop_pts <= 0:
        return 0.0, 0.0
    lo = grid_price(so, -so.g_buys) - so.g_stop_pts if so.g_buys else 0.0
    hi = grid_price(so, so.g_sells) + so.g_stop_pts if so.g_sells else 0.0
    return lo, hi


def grid_stop_hit(so: SmartOrder, price: float) -> bool:
    """Ушла ли цена за последний уровень дальше стопа. Сторона позиции не важна:
    сетка двусторонняя, и выход за любой край означает, что рынок ушёл из неё."""
    if so.g_stop_pts <= 0 or price <= 0:
        return False
    lo, hi = grid_stop_levels(so)
    return bool((lo and price <= lo) or (hi and price >= hi))


def corridor_bounds(so: SmartOrder, now_ms: int, schedule: dict | None = None) -> tuple[float, float]:
    """Где стенки коридора ПРЯМО СЕЙЧАС: (нижняя, верхняя).

    Верхняя — прямая через (c_t1_ms, c_p1) и (c_t2_ms, c_p2), продолженная за
    вторую точку. Нижняя параллельна ей и отстоит на ту же ширину, что была
    задана в первой точке (c_p1 − c_low): угол задаётся один раз и относится ко
    ВСЕМУ коридору, иначе канал незаметно превращался бы в клин.

    ВРЕМЯ ЗДЕСЬ ТОРГОВОЕ, а не календарное (поймал оператор 30.09.2026 на
    треугольнике RTS). Линию он проводит на графике, где ночи, клиринга и
    выходного на оси X нет вовсе; тот же наклон в календарном времени даёт
    другую прямую — тем более пологую, чем больше перерывов между точками, а
    через ночь ошибка кратная. Без расписания (schedule=None) остаётся
    календарное время: это честный откат, но линия будет мягче.
    """
    if schedule:
        dt = market_session.trading_ms_between(schedule, so.c_t1_ms, so.c_t2_ms)
        passed = market_session.trading_ms_between(schedule, so.c_t1_ms, now_ms)
    else:
        dt = so.c_t2_ms - so.c_t1_ms
        passed = now_ms - so.c_t1_ms
    k = passed / dt if dt else 0.0
    top = so.c_p1 + (so.c_p2 - so.c_p1) * k
    if so.c_low2 > 0:
        # Треугольник: у нижней границы свой угол. Сужающийся сходится в апекс,
        # расширяющийся расходится; обе линии продолжаются за вторую точку, как и
        # у коридора, поэтому апекс может оказаться в будущем.
        return so.c_low + (so.c_low2 - so.c_low) * k, top
    return top - (so.c_p1 - so.c_low), top


def corridor_action(so: SmartOrder, price: float, now_ms: int,
                    schedule: dict | None = None) -> tuple[int, int, str]:
    """Что коридор делает на этой цене: (сторона, объём, причина).

    Сторона +1 покупка, −1 продажа, 0 ничего. Объём УЖЕ с учётом переворота:
    из шорта в лонг это 2×qty одной сделкой, потому что заявка должна и закрыть,
    и открыть. Выход по стопу закрывает ровно текущую позицию.
    """
    if so.c_done or price <= 0:
        return 0, 0, ""
    low, top = corridor_bounds(so, now_ms)
    if low >= top:
        # АПЕКС сужающегося треугольника: стенки сошлись, «от какой стенки» смысла
        # больше не имеет. Закрываем позицию и заканчиваем — держать её здесь
        # значит торговать фигуру, которой уже нет.
        if so.c_pos != 0:
            return (-1 if so.c_pos > 0 else 1), abs(so.c_pos), "апекс: стенки сошлись"
        so.c_done = True
        return 0, 0, ""
    stop = float(so.c_stop_pts or 0)
    # СТОП ПЕРВЫМ: цена уже за стенкой дальше допуска — коридор кончился, и
    # спорить с рынком нечем. Проверяется раньше входов, иначе на проколе вверх
    # робот сначала продал бы «от стенки», а потом закрывался бы с убытком.
    if stop > 0 and so.c_pos != 0:
        if so.c_pos < 0 and price >= top + stop:
            return 1, -so.c_pos, "стоп: цена ушла за верхнюю стенку"
        if so.c_pos > 0 and price <= low - stop:
            return -1, so.c_pos, "стоп: цена ушла за нижнюю стенку"
    if price >= top:
        if so.c_pos < 0:
            return 0, 0, ""                    # уже в шорте от этой стенки
        return -1, (so.c_qty or so.qty) + abs(so.c_pos), "продажа от верхней стенки"
    if price <= low:
        if so.c_pos > 0:
            return 0, 0, ""                    # уже в лонге от этой стенки
        return 1, (so.c_qty or so.qty) + abs(so.c_pos), "покупка от нижней стенки"
    return 0, 0, ""


def corridor_after_fire(so: SmartOrder, side: int, qty: int, stop_exit: bool) -> None:
    """Учесть исполненный ход коридора: новая позиция, счётчик переворотов, конец.

    Переворотом считается смена стороны из позиции, а не любой вход: первый вход
    от стенки — это ещё не переворот, иначе лимит в один переворот кончался бы
    сразу после открытия.
    """
    base = so.c_qty or 0
    if stop_exit:
        so.c_pos = 0
        so.c_done = True
        return
    if so.c_pos != 0 and (so.c_pos > 0) != (side > 0):
        so.c_flips += 1
    so.c_pos = side * base
    if so.c_flips_max and so.c_flips >= so.c_flips_max:
        so.c_done = True          # лимит выбран: закрываемся следующим касанием


def blend_avg(pos: int, avg: float, got: int, price: float, side_buy: bool) -> tuple[int, float]:
    """Новая позиция и новая средняя после филла. Возвращает (позиция, средняя).

    Правило простое и то же, что у любого учёта позиции:
      * доливка в ту же сторону — средняя взвешивается по объёму;
      * сокращение — средняя НЕ меняется (реализуется прибыль или убыток, а цена
        оставшегося куска от этого не двигается);
      * переворот через ноль — старой позиции больше нет, средняя становится ценой
        той части филла, что открыла новую сторону;
      * выход в ноль — средней нет вовсе.

    Нужна для режима «только на выход»: без средней нельзя ответить, закрывает ли
    заявка позицию БЕЗ УБЫТКА, а это ровно то, что просил оператор.
    """
    delta = got * (1 if side_buy else -1)
    new_pos = pos + delta
    # ЦЕНА НОЛЬ — НЕ ЦЕНА. Запись о филле может прийти без цены (склад заявок её
    # не знает, подхваченная строка ещё не дочитана), и 02.10.2026 такие нули
    # утянули среднюю сетки 67c52ac651 к 14211 при филлах 85270..86080 — в шесть
    # раз мимо. Позицию считаем всегда, среднюю трогаем только по настоящей цене:
    # соврать средней хуже, чем не обновить её.
    if price <= 0:
        return new_pos, (0.0 if new_pos == 0 else avg)
    if new_pos == 0:
        return 0, 0.0
    if pos == 0:
        return new_pos, price
    if avg <= 0:
        # ПОЗИЦИЯ ЕСТЬ, А СРЕДНЕЙ НЕТ — значит мы её не знали, и взвешивать по нулю
        # нельзя: ноль не «дешёвый вход», а отсутствие знания. 02.10.2026 сетка
        # 41bf3af0dd пришла с позицией +3 и средней 0, и каждый филл по 84840-84940
        # тянул среднюю к нулю — вышло 56476 при реальных ~84900. Для режима «только
        # на выход» это смертельно: с такой средней выход либо не откроется никогда,
        # либо откроется в убыток. Берём цену ПЕРВОГО известного филла как точку
        # отсчёта: она хотя бы настоящая.
        return new_pos, price
    if (pos > 0) == (delta > 0):                      # доливка
        total = abs(pos) + abs(delta)
        return new_pos, (avg * abs(pos) + price * abs(delta)) / total
    if (new_pos > 0) == (pos > 0):                    # сокращение, средняя прежняя
        return new_pos, avg
    return new_pos, price                             # переворот через ноль


def grid_guard_hit(so: SmartOrder, price: float) -> str:
    """Причина включить защиту сетки, или пустая строка. МЕНЯЕТ счётчик касаний.

    Два независимых условия, каждое выключается нулём:
      * исполнено `g_trig_fills` уровней с момента взведения — сетку «пилит»;
      * цена `g_trig_touches` раз коснулась порога `g_trig_move_pct` процентов от
        базы — рынок пошёл трендом, а сетка в тренде набирает против него.

    КАСАНИЕ — ЭТО ВХОД В ЗОНУ, А НЕ ТИК В НЕЙ. Сторож ходит раз в секунду, и без
    этого различия одна минута за порогом дала бы шестьдесят «касаний». Считаем
    только переход снаружи внутрь; возврат к базе снова взводит счёт.

    СТОРОНЫ СЧИТАЮТСЯ ОТДЕЛЬНО. Снимать сетку должен ОДНОСТОРОННИЙ уход: три
    касания верхнего порога это тренд вверх, а касание вверх и касание вниз —
    колебание вокруг базы, то есть ровно то, ради чего сетка и стоит. Суммировать
    их значило бы выключать сетку в её рабочем режиме.

    Зачем вообще несколько касаний: одиночный выброс цены не должен снимать сетку —
    ткнулась и вернулась это шум. Порог 1 = срабатывание на первом же касании.

    Возвращается ТЕКСТ причины, а не флаг: оператор, увидев остановку набора,
    обязан прочитать в журнале, какое условие сработало и на каком числе.
    """
    # УРОВНИ СЧИТАЮТСЯ В ОДНУ СТОРОНУ, А НЕ ВСЕ ПОДРЯД (оператор 02.10.2026: «кол-во
    # касаний в том числе и уровней!» — то же правило, что у касаний цены: с одной
    # стороны, не с двух). Мера — набранная позиция сетки в уровнях, |g_pos|/лот.
    #
    # Почему позиция, а не счётчик филлов. В тот же день на GZZ6 защита сработала
    # на трёх филлах при позиции +5 = ОДИН уровень: сетка честно отрабатывала
    # боковик (вниз, вверх, вниз), а защита сочла это трендом и сняла все покупки.
    # Чередование позицию не наращивает — значит и защиту включать не должно. А
    # тренд с откатами (вниз, вниз, вверх, вниз, вниз) позицию наращивает на три
    # уровня — и его ловит именно позиция; «серия подряд» сбрасывалась бы на каждом
    # откате и пропустила бы его. Бэктест защиты (пятая редакция) говорит то же
    # самое: работает «меньше набирать», а не точный момент — набор и меряем.
    if so.g_trig_fills and so.g_lot > 0:
        levels = abs(so.g_pos) / so.g_lot
        if levels >= so.g_trig_fills:
            where = "вниз (лонг)" if so.g_pos > 0 else "вверх (шорт)"
            return (f"набрано уровней в одну сторону {levels:g} из порога "
                    f"{so.g_trig_fills}: позиция {so.g_pos:+d}, цена ушла {where} "
                    f"(всего исполнено уровней {so.g_fills_done})")
    if not (so.g_trig_move_pct and so.g_base > 0 and price > 0):
        return ""
    moved = (price - so.g_base) / so.g_base * 100.0
    side = ""
    if moved >= so.g_trig_move_pct:
        side = "up"
    elif -moved >= so.g_trig_move_pct:
        side = "down"
    if side and side != so.g_zone_side:
        if side == "up":
            so.g_touch_up += 1
        else:
            so.g_touch_down += 1
    so.g_zone_side = side
    need = so.g_trig_touches if so.g_trig_touches > 0 else 1
    got = so.g_touch_up if side == "up" else so.g_touch_down if side == "down" else 0
    if side and got >= need:
        where = "вверх" if side == "up" else "вниз"
        return (f"цена ушла от базы {where} на {abs(moved):.2f}% при пороге "
                f"{so.g_trig_move_pct:.2f}% ({so.g_base:g} -> {price:g}), "
                f"касаний с этой стороны {got} из {need}")
    return ""


def ensure_cash_basis(so: SmartOrder) -> bool:
    """Завести денежный поток, если он ещё не ведётся. True = поток есть.

    Так выглядит каждая сетка, пережившая выкат этой механики. Берём открытую
    позицию по её средней: прибыль тогда считается ОТ ЭТОГО МОМЕНТА, а не от
    взведения. Приписывать себе заработанное до начала счёта нельзя — этих филлов
    в записи нет.

    Позиция есть, а средней нет (ноль) — базу НЕ заводим. Тогда поток был бы
    нулём, и вся позиция по рынку сошла бы за прибыль: цель сработала бы на
    первом же проходе и закрыла бы позицию рыночной на пустом месте. Средняя уже
    бывала нулевой при живой позиции (02.10.2026, 56476 вместо 84900).
    """
    if so.g_cash_on:
        return True
    if so.g_pos and so.g_avg <= 0:
        return False
    so.g_cash_pts = -so.g_pos * so.g_avg
    so.g_cash_on = True
    return True


def grid_profit_rub(so: SmartOrder, price: float, coef: float) -> float:
    """Прибыль сетки в рублях: денежный поток плюс открытая позиция по рынку.

    `coef` — рублей за пункт (step_cost/price_step). Без него считать НЕЛЬЗЯ:
    пункт не рубль, и 02.10.2026 карточка робота уже показывала −11 ₽ вместо
    −5585 ₽, умножив пункты на чужой коэффициент. Нет коэффициента — нет ответа.
    """
    if price <= 0 or coef <= 0:
        return 0.0
    return (so.g_cash_pts + so.g_pos * price) * coef


def grid_tp_hit(so: SmartOrder, price: float, coef: float) -> str:
    """Причина выйти по цели прибыли, или пустая строка. Ноль цели выключает."""
    if so.g_tp_rub <= 0 or price <= 0 or coef <= 0 or not so.g_cash_on:
        return ""
    got = grid_profit_rub(so, price, coef)
    if got < so.g_tp_rub:
        return ""
    return (f"прибыль сетки {got:,.0f} ₽ достигла цели {so.g_tp_rub:,.0f} ₽ "
            f"(поток {so.g_cash_pts:+,.0f} пт, позиция {so.g_pos:+d} по {price:g})"
            ).replace(",", " ")


def grid_rearm_base(so: SmartOrder, price: float) -> float:
    """База для перевзведения сетки — ТЕКУЩАЯ цена, а не прежняя база.

    Сетку выключило ровно тем, что рынок ушёл от базы; вернуть уровни туда, где
    рынка уже нет, значит выставить половину сетки по ту сторону цены и мгновенно
    налиться (ровно это стоило 43 контрактов 30.09.2026). Цены нет — не
    перевзводим: вслепую ставить сетку нельзя.
    """
    return price if price > 0 else 0.0


def breakeven_price(pos: int, avg: float, step: float, market: float,
                    collar_frac: float) -> float:
    """Цена выхода «только на выход» у сетки: БЕЗУБЫТОК ТЕКУЩЕЙ позиции.

    Оператор 02.10.2026: «только на выход — это выход только из текущей позиции
    без убытка, а не по накопительному результату». Значит цена — средняя
    ТЕКУЩЕЙ позиции (g_avg: доливка взвешивает, сокращение сохраняет, переворот
    сбрасывает), округлённая в сторону без убытка: лонг продаём не ниже, шорт
    покупаем не выше. Никаких уровней сетки выше средней — они ждали прибыли сверх
    безубытка, а этого не просили.

    Рынок уже лучше средней — выходим сразу, но в пределах коллара: лимит, далеко
    пересекающий рынок, агент отобьёт. Цена ставится на половину коллара за
    рынок, то есть исполняется немедленно и не хуже безубытка.
    """
    if pos == 0 or avg <= 0:
        return 0.0
    be = quantize(avg, step, "buy" if pos > 0 else "sell")   # лонг вверх, шорт вниз
    if market <= 0:
        return be
    if pos > 0 and market > be:
        return max(be, quantize(market * (1 - collar_frac / 2), step, "buy"))
    if pos < 0 and market < be:
        return min(be, quantize(market * (1 + collar_frac / 2), step, "sell"))
    return be


def exit_side_qty(pos: int) -> tuple[str, int]:
    """Чем и сколько закрывать позицию: ('buy'|'sell', объём). Вне рынка — ('', 0)."""
    if pos == 0:
        return "", 0
    return ("sell" if pos > 0 else "buy"), abs(pos)


def exit_without_loss(pos: int, avg: float, price: float) -> bool:
    """Закроет ли сделка по этой цене позицию БЕЗ УБЫТКА.

    Лонг закрывается продажей не ниже средней, шорт — покупкой не выше. Средней
    нет (позиция не отслежена) — честно False: «не знаю» не повод рисковать
    убытком, которого оператор запретил.

    КОМИССИЯ ЗДЕСЬ НЕ УЧТЕНА, и это надо знать: равенство цене входа означает
    нулевой результат ДО сборов, то есть с ними небольшой минус. Нужен запас —
    добавим отступ в пунктах отдельным параметром, молча закладывать его нельзя.
    """
    if pos == 0 or avg <= 0 or price <= 0:
        return False
    return price >= avg if pos > 0 else price <= avg


def corridor_closeout(so: SmartOrder) -> tuple[int, int]:
    """Чем закрыть позицию коридора, когда он объявлен законченным: (сторона, объём)."""
    if so.c_pos == 0:
        return 0, 0
    return (-1 if so.c_pos > 0 else 1), abs(so.c_pos)


def _trigger_hit(so: SmartOrder, price: float) -> bool:
    if so.kind == "sl":
        return price <= so.trigger_price if so.side == "sell" else price >= so.trigger_price
    if so.kind == "tp":
        return price >= so.trigger_price if so.side == "sell" else price <= so.trigger_price
    return False


def _trail_step(so: SmartOrder, price: float) -> bool:
    """Advance trailing state; returns True when the retrace fired."""
    if not so.activated:
        if so.trigger_price <= 0:
            so.activated = True
            so.peak = price
        elif (so.side == "sell" and price >= so.trigger_price) or \
             (so.side == "buy" and price <= so.trigger_price):
            so.activated = True
            so.peak = price
        else:
            return False
    if so.side == "sell":
        so.peak = max(so.peak, price)
        return price <= so.peak - so.trail_offset
    so.peak = min(so.peak, price)
    return price >= so.peak + so.trail_offset


def evaluate(orders: list[SmartOrder], code: str, *, last: float, bid: float,
             ask: float, tick_ms: int, now_ms: int,
             filled_client_ids: set[str], step: float,
             session_open: bool | None,
             schedule: dict | None = None) -> list[Fire | Cancel]:
    """One watcher pass for one instrument. Mutates trailing bookkeeping on the
    orders; returns the actions to execute. Deterministic, no I/O.

    Price basis: LAST trade ONLY (QUIK stop-orders trigger on last). Никакого
    mid: середина НЕСПАРЕННОГО предторгового стакана — не цена, по которой
    что-то торгуется, а сторож принимал её за рынок.

    ТОРГУЕТ ЛИ БИРЖА — обязательное условие (`session_open`, оракул
    trader/market_session.py; аукцион открытия у него НЕ торги). Свежесть кадра
    (`tick_ms`) — это время ПРИХОДА, а не время сделки: вне сессии и сразу после
    перезапуска агента QUIK переиздаёт нерыночные значения, и они приезжают
    «свежими». 06.08.2026 на этом trail_tp buy 19 RIU6 активировался по 89 120
    (такой цены за всю жизнь заявки на рынке не было), сработал в 06:55 —
    в аукционе открытия, до 07:00 — и купил 19 контрактов по 90 150.
    """
    actions: list[Fire | Cancel] = []
    price = last
    fresh = tick_ms > 0 and (now_ms - tick_ms) <= _STALE_TICK_MS
    trading = session_open is True

    armed = [o for o in orders if o.status == "armed" and o.code == code]
    fired_groups: set[str] = set()

    for so in armed:
        if so.good_till_ms and now_ms > so.good_till_ms:
            so.status = "expired"
            continue

        if not trading:
            continue  # аукцион/клиринг/ночь: ни следить, ни стрелять

        if so.kind == "on_fill":
            if so.watch_client_id in filled_client_ids:
                px = so.child_price or marketable_price(so.side, bid, ask, price, step)
                if px > 0:
                    actions.append(Fire(so, quantize(px, step, so.side)))
                    if so.oco_group:
                        fired_groups.add(so.oco_group)
            continue

        if not fresh or price <= 0:
            continue  # never act on a dead/stale feed

        if so.kind in ("corridor", "triangle"):
            if so.c_done and so.c_pos != 0:
                side, qty = corridor_closeout(so)
                why = "переворты исчерпаны: закрываем позицию"
            else:
                side, qty, why = corridor_action(so, price, now_ms, schedule)
            if side and qty > 0:
                px = marketable_price("buy" if side > 0 else "sell", bid, ask, price, step)
                if px > 0:
                    actions.append(Fire(so, px))
                    so.side = "buy" if side > 0 else "sell"
                    so.qty = qty
                    so.note = why
            continue

        hit = _trail_step(so, price) if so.kind in _TRAILING else _trigger_hit(so, price)
        if hit:
            px = marketable_price(so.side, bid, ask, price, step)
            if px > 0:
                actions.append(Fire(so, px))
                if so.oco_group:
                    fired_groups.add(so.oco_group)

    if fired_groups:
        fired_ids = {a.so.so_id for a in actions if isinstance(a, Fire)}
        for so in armed:
            if (so.status == "armed" and so.oco_group in fired_groups
                    and so.so_id not in fired_ids):
                actions.append(Cancel(so, "OCO: сработала парная заявка"))
    return actions


def _bracket_group(parent: SmartOrder) -> str:
    """Связка OCO для защитной пары. Стоп и тейк стерегут ОДНУ позицию: сработал
    один — второй обязан сняться, иначе он откроет позицию в обратную сторону.
    Своя группа родителя уважается; если её нет, заводим по его id."""
    return parent.oco_group or f"br:{parent.so_id}"


def _protective(parent: SmartOrder, entry_price: float, now: int, kind: str) -> SmartOrder | None:
    """Защитная заявка ПОСЛЕ входа по родительской (trail/on_fill).

    Родитель только ВХОДИТ в позицию и после срабатывания забывает про неё:
    без этих заявок ни выйти по стопу, ни забрать прибыль нечем.
      sl — противоположная сторона на sl_offset пунктов ПРОТИВ входа
           (купили по 89 000, стоп 300 -> продажа при цене <= 88 700);
      tp — противоположная сторона на tp_offset пунктов В ПОЛЬЗУ входа
           (купили по 89 000, тейк 500 -> продажа при цене >= 89 500).

    Точка отсчёта — цена дочерней заявки родителя в момент срабатывания. Как
    только сторож узнает РЕАЛЬНУЮ среднюю цену исполнения, уровни пересчитываются
    от неё (см. rebase_protective).
    """
    offset = {"sl": parent.sl_offset, "tp": parent.tp_offset,
              "trail_sl": parent.trail_after}.get(kind, 0.0)
    level = {"sl": parent.sl_price, "tp": parent.tp_price}.get(kind, 0.0)
    if (offset <= 0 and level <= 0) or entry_price <= 0:
        return None
    exit_side = "sell" if parent.side == "buy" else "buy"
    if level > 0 and _level_wrong_side(parent, entry_price, kind, level):
        # Вход случился уже за уровнем: ставить такой тейк или стоп нельзя, он
        # закрыл бы позицию сразу и не по делу. РЕШЕНИЕ ОПЕРАТОРА 18.09.2026:
        # ничего не выдумывать, сказать человеку (тревогу шлёт сторож).
        return None
    # Подтягивающая уровня не имеет: она ведёт его сама от цены. Поэтому
    # trigger_price остаётся нулём, а шаг едет в trail_offset.
    if kind == "trail_sl":
        return SmartOrder(
            so_id=new_id(), kind="trail_sl", code=parent.code, side=exit_side,
            qty=parent.qty, trail_offset=offset, oco_group=_bracket_group(parent),
            good_till_ms=parent.good_till_ms, parent_id=parent.so_id, created_ms=now,
            note=f"подтягивающая от {parent.so_id}: вход {entry_price:g}, {offset:g} п.")
    # Стоп — против входа, тейк — в сторону входа.
    sign = -1 if kind == "sl" else 1
    trigger = entry_price + sign * offset * (1 if parent.side == "buy" else -1)
    if trigger <= 0:
        return None
    if level > 0 and kind != "trail_sl":
        trigger = level
        if kind == "tp" and parent.tp_trail > 0:
            return SmartOrder(
                so_id=new_id(), kind="trail_tp", code=parent.code, side=exit_side, qty=parent.qty,
                trigger_price=trigger, trail_offset=parent.tp_trail, oco_group=_bracket_group(parent),
                good_till_ms=parent.good_till_ms, parent_id=parent.so_id, created_ms=now,
                note=(f"следящий тейк от {parent.so_id}: активация по уровню {trigger:g}, "
                      f"откат {parent.tp_trail:g} п. (вход {entry_price:g})"))
        return SmartOrder(
            so_id=new_id(), kind=kind, code=parent.code, side=exit_side, qty=parent.qty,
            trigger_price=trigger, oco_group=_bracket_group(parent),
            good_till_ms=parent.good_till_ms, parent_id=parent.so_id, created_ms=now,
            note=(f"{'защитный стоп' if kind == 'sl' else 'тейк'} от {parent.so_id}: "
                  f"уровень {trigger:g} (вход {entry_price:g})"))
    if kind == "tp" and parent.tp_trail > 0:
        # Следящий тейк = обычная trail_tp стороны выхода: trigger_price это уровень
        # активации, trail_offset это откат. Движок ведёт её штатно, связка OCO та же.
        return SmartOrder(
            so_id=new_id(), kind="trail_tp", code=parent.code, side=exit_side, qty=parent.qty,
            trigger_price=trigger, trail_offset=parent.tp_trail, oco_group=_bracket_group(parent),
            good_till_ms=parent.good_till_ms, parent_id=parent.so_id, created_ms=now,
            note=(f"следящий тейк от {parent.so_id}: вход {entry_price:g}, "
                  f"активация {offset:g} п., откат {parent.tp_trail:g} п."))
    what = "защитный стоп" if kind == "sl" else "тейк"
    return SmartOrder(
        so_id=new_id(), kind=kind, code=parent.code, side=exit_side, qty=parent.qty,
        trigger_price=trigger, oco_group=_bracket_group(parent),
        good_till_ms=parent.good_till_ms, parent_id=parent.so_id,
        created_ms=now,
        note=f"{what} от {parent.so_id}: вход {entry_price:g}, {offset:g} п.")


def _level_wrong_side(parent: SmartOrder, entry_price: float, kind: str, level: float) -> bool:
    """Уровень оказался НЕ с той стороны от входа: тейк ниже покупки, стоп выше."""
    long_side = parent.side == "buy"
    if kind == "tp":
        return level <= entry_price if long_side else level >= entry_price
    return level >= entry_price if long_side else level <= entry_price


def level_violations(parent: SmartOrder, entry_price: float) -> list[str]:
    """Какие заданные ЦЕНОЙ блоки после сделки не удалось поставить и почему.

    Человеку это надо сказать немедленно: он думает, что позиция под защитой."""
    out: list[str] = []
    if entry_price <= 0:
        return out
    for kind, level, what in (("sl", parent.sl_price, "стоп"), ("tp", parent.tp_price, "тейк")):
        if level > 0 and _level_wrong_side(parent, entry_price, kind, level):
            side = "выше" if parent.side == "buy" else "ниже"
            out.append(f"{what} по уровню {level:g} не поставлен: вход {entry_price:g} уже {side} него")
    return out


def protective_sl(parent: SmartOrder, entry_price: float, now: int) -> SmartOrder | None:
    return _protective(parent, entry_price, now, "sl")


def protective_tp(parent: SmartOrder, entry_price: float, now: int) -> SmartOrder | None:
    return _protective(parent, entry_price, now, "tp")


def protective_trail(parent: SmartOrder, entry_price: float, now: int) -> SmartOrder | None:
    return _protective(parent, entry_price, now, "trail_sl")


#: Дочерняя заявка создана, но ЕЩЁ НЕ ВЗВЕДЕНА: филл основной не подтверждён.
#: active() берёт только "armed", поэтому спящая инертна по построению.
WAITING = "waiting"


def protective_children(parent: SmartOrder, entry_price: float, now: int) -> list[SmartOrder]:
    """Все заявки «после сделки» одной связкой. Стоп и подтягивающая взаимно
    исключены валидацией, поэтому здесь их можно собирать не разбираясь.

    РОЖДАЮТСЯ СПЯЩИМИ. 01.10.2026 основную заявку оператора на продажу 10
    отверг коллар агента («price beyond collar», филл ноль) — а дочерняя защита
    об этом не знала, была взведена сразу и через секунду КУПИЛА 10 контрактов:
    чистая позиция, которой никто не заказывал. Уровни при этом считались от
    предполагаемой цены входа 86060, которой в рынке не было, поэтому стоп
    оказался позади рынка и сработал мгновенно.

    Защита имеет смысл только для позиции, которая ОТКРЫЛАСЬ. Пока филл основной
    не подтверждён фактом (таблицей сделок, а не фактом отправки заявки),
    дочерняя спит; основная умерла без филла — дочерние снимаются вместе с ней.
    """
    kids = [c for c in (protective_sl(parent, entry_price, now),
                        protective_tp(parent, entry_price, now),
                        protective_trail(parent, entry_price, now)) if c is not None]
    for c in kids:
        c.status = WAITING
    return kids


def superseded_stops(book: list[SmartOrder], fresh: SmartOrder) -> list[SmartOrder]:
    """Чужие стопы на ТУ ЖЕ позицию, которые новая подтягивающая отменяет.

    Оператор ставит подтягивающую на уже открытую позицию, и если на ней висел
    прежний стоп — их станет два. Сработает ближний, а дальний останется взведён
    и следующим ходом ОТКРОЕТ позицию в обратную сторону: это не защита, а вход
    в рынок без ведома оператора. Позиция определяется парой (инструмент,
    сторона закрытия): всё, что закрывает ту же позицию тем же направлением.

    Чистая функция: решение принимает движок, снимает заявки сторож.
    """
    if fresh.kind != "trail_sl":
        return []
    return [o for o in book
            if o.status == "armed" and o.so_id != fresh.so_id
            and o.kind in ("sl", "trail_sl")
            and o.code == fresh.code and o.side == fresh.side]


def rebase_protective(children: list[SmartOrder], parent: SmartOrder,
                      real_entry: float) -> bool:
    """Пересчитать уровни защитных заявок от РЕАЛЬНОЙ цены исполнения входа.

    Создаются они по цене дочерней заявки (маркетабельной), а исполняется она
    часто лучше лимита — на тик-два. Пока заявка ещё взведена, честнее подвинуть
    её на фактический вход, чем оставлять уровень от предполагаемой цены."""
    if real_entry <= 0:
        return False
    moved = False
    for c in children:
        # СПЯЩИЕ ПЕРЕСЧИТЫВАЮТСЯ ТОЖЕ, и ради них всё и затевалось: дочерняя
        # заявка ждёт подтверждения филла именно для того, чтобы встать от
        # ФАКТИЧЕСКОЙ цены входа. Пропустить её здесь значило бы взвести потом
        # по предполагаемой цене — той самой ошибке, от которой уходим.
        if c.status not in ("armed", WAITING) or c.parent_id != parent.so_id:
            continue
        kind = c.kind
        if kind == "trail_tp":
            # Следящий тейк строится как «tp». Активированный уже ведёт экстремум:
            # двигать его уровень активации задним числом бессмысленно.
            if c.activated:
                continue
            kind = "tp"
        fresh = _protective(parent, real_entry, c.created_ms, kind)
        if fresh is None or abs(fresh.trigger_price - c.trigger_price) < 1e-9:
            continue
        c.trigger_price = fresh.trigger_price
        c.note = fresh.note + " (уровень от фактической цены входа)"
        moved = True
    return moved


# ---- book with JSON persistence (survives an STL restart) ----

class SmartOrderBook:
    """All smart orders + save/load. The watcher task is the single mutator at
    runtime; API handlers run on the same event loop, so plain attrs are safe."""

    def __init__(self, path: str) -> None:
        self._path = path
        self.orders: list[SmartOrder] = []

    def load(self) -> None:
        if not os.path.exists(self._path):
            return
        try:
            with open(self._path, encoding="utf-8") as f:
                raw = json.load(f)
            self.orders = [SmartOrder(**o) for o in raw]
        except Exception:
            # A corrupt file must not kill STL startup; start empty, keep the
            # broken file for post-mortem.
            try:
                os.replace(self._path, self._path + ".corrupt")
            except OSError:
                pass
            self.orders = []

    def save(self) -> None:
        d = os.path.dirname(self._path)
        if d:
            os.makedirs(d, exist_ok=True)
        tmp = self._path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump([asdict(o) for o in self.orders], f, ensure_ascii=False, indent=1)
        os.replace(tmp, self._path)

    def add(self, so: SmartOrder) -> None:
        self.orders.append(so)
        self.save()

    def get(self, so_id: str) -> SmartOrder | None:
        return next((o for o in self.orders if o.so_id == so_id), None)

    def active(self) -> list[SmartOrder]:
        return [o for o in self.orders if o.status == "armed"]

    def codes(self) -> set[str]:
        return {o.code for o in self.active()}


# Доля цены инструмента, с которой «пункты» перестают быть похожими на пункты.
# Половина: реальный блок после сделки - это сотни пунктов при цене в десятки тысяч,
# а ошибочно введённая цена всегда около самой цены.
_PRICE_IN_POINTS_FRAC = 0.5


# Насколько инструмент должен отстать от самого свежего, чтобы считаться молчащим.
# Истёкший контракт остаётся в таблицах QUIK и выглядит нормальным: у RIU6 18.09
# в фиде лежала вчерашняя цена 84460 при живом RIZ6 83440, и заявка на 10
# контрактов ждала уровня, которого в природе уже нет (оператор, 18.09.2026).
_SILENT_LAG_MS = 30 * 60 * 1000


def silent_code(code: str, ages_ms: dict[str, int]) -> str | None:
    """Человеческое объяснение, почему по инструменту нечего сторожить, или None.

    ages_ms - возраст последней котировки по каждому известному инструменту.
    Сравниваем не с часами, а ДРУГ С ДРУГОМ: ночью молчат все, и абсолютный
    возраст ничего не значит, а отставание от самого живого - значит всегда."""
    mine = ages_ms.get(code)
    if mine is None:
        return f"по {code} нет ни одной котировки: инструмент не подключён к торговле"
    if not ages_ms:
        return None
    freshest = min(ages_ms.values())
    if mine - freshest > _SILENT_LAG_MS:
        return (f"по {code} котировок нет уже {mine / 3_600_000:.1f} ч, а по другим инструментам "
                f"они идут: контракт истёк или снят с торгов. Сторожу нечего проверять")
    return None


def new_id() -> str:
    return uuid.uuid4().hex[:10]


def now_ms() -> int:
    return int(time.time() * 1000)
