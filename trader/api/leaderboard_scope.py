"""Какие строки хитпарада считаются ПРЕДЛОЖЕНИЕМ, а какие служебными.

01.10.2026 оператор увидел в компаньоне «кандидат: supertrend RIU6 +63 740 ₽,
RF 4.8». Кандидатом это не было: строка из ПЛАЦЕБО гейта UNI-kelt — 50 случайных
трендовых векторов, кампания camp-20261001-gatekelt1001g6supw3005. Лампа
сработала честно по своему правилу (прибыль, RF>=3, сделок>=30 за 24 ч), но
служебные прогоны лежали в лидерборде как обычные (письмо backtests).

Договорённость с backtests: проверочные, плацебо и калибровочные кампании
называются camp-YYYYMMDD-gate*, -plc*, -exec*. Их строки не попадают ни в лампу,
ни в витрину: случайный вектор, выигравший в лотерею, предлагать оператору
нельзя — он выглядит ровно как находка.

Предикат ОДИН на оба запроса. Два одинаковых условия в двух SQL-строках
расходятся — вопрос только когда; у нас это уже было с геометрией коридора.
"""

from __future__ import annotations

import re

# gate — гейт/плацебо, plc — placebo, exec — калибровка издержек исполнения.
SERVICE_PREFIXES = ("gate", "plc", "exec")

# camp-ГГГГММДД-<имя>: служебным считается то, что начинается с префикса СРАЗУ
# после даты. Поиск префикса где угодно в строке поймал бы живую кампанию со
# словом «exec» в середине имени.
_SERVICE_RE = re.compile(
    r"^camp-\d{8}-(?:" + "|".join(SERVICE_PREFIXES) + r")", re.IGNORECASE)

# Тот же отбор для SQL. `~*` — регистронезависимое совпадение по регэкспу в
# Postgres. NULL в campaign_run служебным НЕ считаем: имени нет — судить не о чем,
# а молча прятать строки без имени значит терять находки.
SQL_NOT_SERVICE = (
    "(campaign_run IS NULL OR campaign_run !~* '^camp-[0-9]{8}-(gate|plc|exec)')"
)


def is_service_campaign(name: str | None) -> bool:
    """Служебный ли это прогон: плацебо, гейт, калибровка."""
    return bool(name) and _SERVICE_RE.match(str(name)) is not None
