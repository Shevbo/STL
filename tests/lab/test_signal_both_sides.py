"""Ни одна стратегия реестра не должна быть заперта в одну сторону на своём окне.

Это ровно тот баг, что стоил живому MACD trend A шести суток односторонней торговли:
знак сигнала залипал на +1 НАВСЕГДА, робот сделал 778 закрытий лонга и ноль шортов,
а причина была не в логике сигнала, а в ОКНЕ — `make_on_bar` зовёт signal() ровно на
`warmup(params)` последних барах, и если окно короче самой длинной EMA, она не
успевает разойтись с сигнальной линией.

Поэтому проверяем не «есть ли в коде ветка на шорт», а факт: на своём окне и на своих
дефолтных параметрах стратегия выдаёт ОБА знака на ряде с явными разворотами.
"""
import math
from types import SimpleNamespace

import pytest

from trader.lab.strategies.library import REGISTRY

# Ряд должен кормить ВСЕ семейства сразу: тренды в обе стороны (кроссоверы), рябь
# (пробои каналов) и РЕЗКИЕ ИМПУЛЬСЫ (без них не рождается ни FVG, ни order block —
# им нужен разрыв между несоседними барами). Детерминирован: тест не зависит от
# случайности. High/low считаем от ХОДА бара, а не постоянной лентой: с лентой
# фиксированной ширины разрыв не образуется в принципе, и паттерновые стратегии
# ложно выглядели «запертыми в одну сторону».
_N = 5000
_SEED = 12345


def _series() -> list[float]:
    px, s, out = 90000.0, _SEED, []
    for i in range(_N):
        s = (1103515245 * s + 12345) % (1 << 31)      # LCG: воспроизводимо и без random
        drift = 4000 * math.sin(2 * math.pi * i / 1200) - 4000 * math.sin(2 * math.pi * (i - 1) / 1200)
        step = drift + (s / (1 << 31) - 0.5) * 120
        if i % 47 == 0:                                # импульс: рождает гэпы и блоки
            step += 600 * (1 if (s >> 10) % 2 else -1)
        px += step
        out.append(px)
    return out


_PX = _series()
BARS = []
for i, c in enumerate(_PX):
    o = _PX[i - 1] if i else c
    BARS.append(SimpleNamespace(close=c, open=o, high=max(o, c) + 15, low=min(o, c) - 15,
                                volume=100 + (i % 7), time=1_780_000_000 + i * 60))


MIN_SIGNALS = 25          # меньше — статистики нет, вывод делать не о чем

# Синтетика неприменима: уровни строятся от HLC ПРЕДЫДУЩЕГО ДНЯ, а гладкий ряд не даёт
# дневной структуры — цена дотягивается до S1 и не дотягивается до R1. Проверено на
# ЖИВЫХ барах RIU6 M1 (01.06-05.08.2026): 1321 лонг против 788 шортов, обе стороны на
# месте. Подгонять ряд под эту стратегию значило бы сломать его для остальных.
SYNTHETIC_BLIND = {"pivot_reversal"}


def _dirs(spec, p, need: int) -> dict:
    """Счётчик направленных сигналов (без 0/None) на окне `need`."""
    out: dict = {}
    for i in range(need, _N, 13):
        try:
            v = spec["signal"](BARS[i - need:i], p)
        except Exception as exc:  # noqa: BLE001 — падение окна ловит отдельный тест
            pytest.fail(f"сигнал падает на окне {need}: {exc}")
        if v in (1, -1):
            out[v] = out.get(v, 0) + 1
    return out


@pytest.mark.parametrize("sid", sorted(REGISTRY))
def test_strategy_can_go_both_ways(sid):
    """Ловим ровно два состояния, оба реально стоившие денег:

    ЗАПЕРТА В ОДНУ СТОРОНУ — стратегия торгует, но знак только один. Так живой
    MACD trend A шесть суток делал лонги и ни одного шорта.

    ОКНО ДУШИТ СИГНАЛ — на своём окне молчит совсем, а на вчетверо длиннее торгует:
    индикатор-фильтр не успевает прогреться (так был устроен rsi_trend: EMA(50) на
    52 барах, ноль сигналов вообще).

    Молчание И на длинном окне не считаем провалом: значит синтетика не даёт этой
    стратегии её паттерн, а не что она сломана.
    """
    if sid in SYNTHETIC_BLIND:
        pytest.skip(f"{sid}: синтетика неприменима, проверено на живых барах")
    spec = REGISTRY[sid]
    p = dict(spec["default_params"])
    p.setdefault("symbol", "RIU6")
    need = int(spec["warmup"](p))
    if need >= _N - 500:
        pytest.skip(f"окно {need} длиннее тестового ряда")
    cnt = _dirs(spec, p, need)
    n = sum(cnt.values())
    # Порог выборки. Без него тест ловит шум: pivot_reversal на синтетике даёт пару
    # лонгов и ноль шортов, а на ЖИВЫХ барах RIU6 — 1321 и 788, то есть исправен.
    # Один-два сигнала ничего не доказывают ни в ту, ни в другую сторону.
    if n >= MIN_SIGNALS:
        assert len(cnt) == 2, (
            f"{sid}: на окне {need} из {n} сигналов ВСЕ {next(iter(cnt))} — "
            f"заперта в одну сторону")
        return
    wide = min(need * 4, _N - 200)
    wide_n = sum(_dirs(spec, p, wide).values())
    assert wide_n < MIN_SIGNALS, (
        f"{sid}: на своём окне {need} сигналов {n}, а на {wide} — {wide_n}: "
        f"окно душит сигнал, индикатор не успевает прогреться")
