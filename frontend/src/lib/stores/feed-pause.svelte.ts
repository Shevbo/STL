// Пауза источника позиций и счёта.
//
// Finam REST отдаёт 500/503 четвёртые сутки (29.09.2026 — 1235 раз, 30.09 —
// 1053), и оператор решил парковать Finam до востребования: опрос в WsHub
// выключается тем же переключателем `exchange_interface`, которым выбирается
// брокер-адаптер (письмо real-trade 01.10.2026).
//
// Экран обязан сказать об этом словами. Молча замолчавшие поля позиций и счёта
// читаются как «позиций нет» и «на счету ноль», а пустое поле НЕ ноль — на этом
// в проекте уже горели не раз.

let _reason = $state('');

export const feedPauseStore = {
  /** Текст причины; пусто — источник живой. */
  get reason() { return _reason; },
  get paused() { return _reason !== ''; },
  set(reason: string) { _reason = reason || ''; },
};
