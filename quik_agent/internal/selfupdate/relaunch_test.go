package selfupdate

import "testing"

// ИНВАРИАНТ: там, где подъём невозможен, SpawnRelaunch обязана вернуть ОШИБКУ, а
// не тихое «ок». На этом держится вся безопасность команды RESTART: агент выходит
// ТОЛЬКО если подъём запланирован. 02.10.2026 выход без подъёма оставил живую
// торговлю без моста до прихода оператора к консоли VDS.
//
// Тест стоит на non-Windows сборке (на ней и гоняется CI агента): здесь подъём не
// поддержан, и молчаливый успех означал бы, что боевой код выйдет навсегда.
func TestSpawnRelaunchReportsFailureInsteadOfSilentOK(t *testing.T) {
	if err := SpawnRelaunch(t.TempDir()); err == nil {
		t.Fatal("SpawnRelaunch вернула nil там, где поднять агента нечем: " +
			"вызывающий примет это за успех и выйдет насовсем")
	}
}
