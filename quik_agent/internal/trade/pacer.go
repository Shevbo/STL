package trade

import (
	"sync"
	"time"
)

// ОГРАНИЧИТЕЛЬ ЧАСТОТЫ ТРАНЗАКЦИЙ К QUIK.
//
// Требование оператора 01.10.2026: больше 15 транзакций в секунду в QUIK
// передавать НЕЛЬЗЯ — сверх этого брокер берёт 5 рублей за КАЖДУЮ. Это не
// теория: сетка «радиация» на 25 уровней выставляется одной пачкой, сторож
// умных заявок переставляет стенки, роботы шлют свои заявки, и все они идут
// через один и тот же мост. Поодиночке каждый источник безобиден, вместе они
// дают всплеск — ровно та же логика, что и у предохранителя по экспозиции:
// незаконна не отдельная заявка, а серия.
//
// Поэтому ограничитель стоит в ОДНОМ месте на выходе (Bridge.send), а не у
// каждого источника: источников много, выход один, и только здесь видно их
// сумму. Это же место переживает появление новых источников, о которых автор
// ограничителя не знал.
//
// Механика простая и намеренно тупая: заявки не отбрасываются, а ВЫСТРАИВАЮТСЯ
// В ОЧЕРЕДЬ. Каждая получает свой слот не раньше, чем через 1/15 секунды после
// предыдущей; порядок сохраняется (кто пришёл раньше, тот и уйдёт раньше).
// Отбрасывать нельзя: потерянная транзакция это потерянная заявка, а у защитной
// заявки потеря означает незакрытую позицию.
//
// ПОТОЛОК, ЗНАТЬ О НЁМ: очередь единая, без приоритетов. Защитный стоп,
// пришедший следом за пачкой из 25 уровней сетки, будет ждать свой слот до
// полутора секунд. Если это окажется дорого — вводить отдельную очередь для
// снятий и рыночных заявок, то есть для всего, что УМЕНЬШАЕТ риск. Пока не
// ввожу: приоритеты без доказанной нужды это лишняя сложность на денежном пути.
const quikMaxTxPerSec = 15

type txPacer struct {
	mu     sync.Mutex
	nextAt time.Time
	perTx  time.Duration
	now    func() time.Time
	sleep  func(time.Duration)
}

func newTxPacer(perSec int) *txPacer {
	if perSec <= 0 {
		perSec = quikMaxTxPerSec
	}
	return &txPacer{
		perTx: time.Second / time.Duration(perSec),
		now:   time.Now,
		sleep: time.Sleep,
	}
}

// wait занимает следующий свободный слот и ждёт до него. Возвращает, сколько
// пришлось ждать, — для журнала: всплески надо видеть, а не догадываться о них.
func (p *txPacer) wait() time.Duration {
	if p == nil {
		return 0
	}
	p.mu.Lock()
	now := p.now()
	if p.nextAt.Before(now) {
		p.nextAt = now
	}
	at := p.nextAt
	p.nextAt = p.nextAt.Add(p.perTx)
	p.mu.Unlock()

	d := at.Sub(now)
	if d > 0 {
		p.sleep(d)
	}
	return d
}
